public class Main {
    public static void main(String[] args){
        System.out.println(Math.max(5, 10)); //encontra o maior
        System.out.println(Math.min(5, 10)); //encontra o menor
        System.out.println(Math.sqrt(64)); //8
        System.out.println(Math.abs(-4.7)); //4.7
        System.out.println(Math.pow(2, 8)); //^8
        System.out.println(Math.round(4.6)); //5
        System.out.println(Math.ceil(4.1)); //5
        System.out.println(Math.floor(4.9)); //4
        System.out.println(Math.random()); //gera numero aleatorio

    }
}